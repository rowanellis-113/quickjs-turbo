"""Activation-owned object-literal structures for synchronous JS next calls.

Research prototype: preserve the complete inherited VM/core, append the previous two C
entries and one qualifying leaf gate, and route only independently decoded CALL/JMP operands. Strong shape
references live on the native activation stack and are released on every VM
exit. They are external roots, not untraced bytecode-owned edges. No global
runtime registry and no change to core types, bytecode or frame sizes.
"""

