def module(source, name):
    import importlib.util

    sp = importlib.util.spec_from_file_location(
        "iterator_checkpoint_" + name.replace("-", "_"), _frame_tool_path(name + ".py")
    )
    m = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(m)
    return m


def function(text, signature):
    start = text.index(signature)
    begin = text.index("{", start)
    end = begin + 1
    depth = 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[start:end] + "\n"


def generate(source, build, out):
    inherited = _frame_generated_file(build, "quickjs-interpreter-iterator.c")
    text = inherited.read_text(encoding="utf-8")
    marker = "/* Generated by tools/generate-slow.py; do not edit. */"
    prefix = text[: text.index(marker)]
    validator = function(prefix, "FRAME_CODE bool JS_FrameIteratorValidate(")
    prefix = prefix.replace(
        validator, "extern bool JS_FrameIteratorValidate(JSFunctionBytecode *b);\n"
    )
    prefix = prefix.replace('section(".qjsiter")', 'section(".qjsitcp")')
    slow = text[
        text.index(marker) : text.index("\n/* One opcode, original ownership/coercion body")
    ]
    slow = slow.replace("JS_FrameIteratorSlow(", "JS_FrameIteratorCheckpointSlow(")
    original = slow[
        slow.index("    CASE(OP_for_of_next):") : slow.index("    CASE(OP_iterator_close):")
    ]
    replacement = r"""
    CASE(OP_for_of_next):
        {
            int offset=-3-pc[0];
            if (FRAME_CHECKPOINT(frame)) {
                JSValue obj,value;
                int done;
                /* Ordinary return consumed the duplicated call operands and
                   wrote its owned result at the original output slot. */
                sp=sf->cur_sp;
                FRAME_CLEAR_CHECKPOINT(frame);
                state->iterator_checkpoint_depth--;
                obj=sp[0];
                pc++;
                sf->cur_pc=pc;
                frame->saved_sp=sp;
                value=JS_FrameIteratorCheckpointValue(ctx,obj,&done);
                if (done || JS_IsException(value)) {
                    JS_FreeValue(ctx,sp[offset]);
                    sp[offset]=JS_UNDEFINED;
                    if (JS_IsException(value))goto exception;
                    JS_FreeValue(ctx,value);
                    value=JS_UNDEFINED;
                }
                sp[0]=value;
                sp[1]=js_bool(done);
                sp+=2;
                goto dispatch;
            }
            if (js_frame_iterator_checkpoint_admit(frame,sp,offset)) {
                state->frame=frame;state->segment=segment;state->used_bytes=used_bytes;
                state->pc=pc-1;state->sp=sp;
                js_frame_finish_c(state);
                return JS_FrameIteratorCheckpointPush(state);
            }
            pc++;
            sf->cur_pc=pc;
            if (JS_FrameIteratorSlowNext(ctx,sp,offset))goto exception;
            sp+=2;
        }
        BREAK;
"""
    slow = slow.replace(original, replacement)
    hook = r"""
    /* A next call/push failure skips IteratorClose, just as js_for_of_next.
       The original cached slots own duplicates throughout cleanup. */
    if (FRAME_CHECKPOINT(frame)) {
        JSValue *iterator_sp=sf->cur_sp;
        int iterator_offset=-3-sf->cur_pc[1];
        pc=sf->cur_pc+2;
        FRAME_CLEAR_CHECKPOINT(frame);
        state->iterator_checkpoint_depth--;
        JS_FreeValue(ctx,iterator_sp[iterator_offset]);
        iterator_sp[iterator_offset]=JS_UNDEFINED;
    }
"""
    assert slow.count("exception:\n    sf->cur_pc = pc;") == 1
    slow = slow.replace(
        "exception:\n    sf->cur_pc = pc;", "exception:\n" + hook + "    sf->cur_pc = pc;"
    )
    backtrace = """    if (needs_backtrace(rt->current_exception) || JS_IsUndefined(ctx->error_back_trace))
        build_backtrace(ctx, rt->current_exception, JS_UNDEFINED, NULL, 0, 0, 0);"""
    assert slow.count(backtrace) == 1
    slow = slow.replace(
        backtrace,
        """    if (needs_backtrace(rt->current_exception) || JS_IsUndefined(ctx->error_back_trace)) {
        JSFrame *trace_frame;
        for(trace_frame=frame;trace_frame;trace_frame=js_frame_parent(trace_frame))
            if(FRAME_CHECKPOINT(trace_frame))trace_frame->sf.cur_pc+=2;
        build_backtrace(ctx, rt->current_exception, JS_UNDEFINED, NULL, 0, 0, 0);
        for(trace_frame=frame;trace_frame;trace_frame=js_frame_parent(trace_frame))
            if(FRAME_CHECKPOINT(trace_frame))trace_frame->sf.cur_pc-=2;
    }""",
    )
    core = _frame_source_file(source, "quickjs.c").read_text(encoding="utf-8")
    next_body = function(core, "static JSValue JS_IteratorNext(")
    tail = next_body[next_body.index("    if (JS_IsException(obj))") :]
    value = (
        """
FRAME_CODE JSValue JS_FrameIteratorCheckpointValue(JSContext *ctx,JSValue obj,int *pdone)
{
    JSValue value,done_val;
    int done=2;
    if (!JS_IsObject(obj)) {
        JS_FreeValue(ctx,obj);
        JS_ThrowTypeError(ctx,"iterator must return an object");
        *pdone=false;
        return JS_EXCEPTION;
    }
"""
        + tail
    )
    helpers = r"""
_Static_assert(sizeof(JSFrame)==128 && offsetof(JSFrame,saved_sp)==104 &&
               offsetof(JSFrame,pending)==126,"retain ordinary frame ABI");
_Static_assert(offsetof(JSStackFrame,cur_sp)==QJS_ABI_OFF_JSStackFrame_cur_sp && FRAME_STACK_CORO_OFFSET_VALID,
               "continuation is a paused ordinary frame, never a coroutine");
_Static_assert(FRAME_ROOT_OFFSET==62 && offsetof(JSFrame,sf)==0 &&
               offsetof(JSStackFrame,prev_frame)==0,"leaf walks private parents only");
_Static_assert(JS_CLASS_BYTECODE_FUNCTION==13,"leaf admits ordinary bytecode methods");
#ifdef QJS_INTERP_FRAME_DIAGNOSTICS
_Static_assert(offsetof(JSFrameRegisterState,exception_pending)==2296,"leaf diagnostic state ABI");
_Static_assert(offsetof(JSFrameRegisterState,iterator_checkpoint_depth)==2300,"leaf diagnostic checkpoint count");
#else
_Static_assert(offsetof(JSFrameRegisterState,exception_pending)==160,"leaf release state ABI");
_Static_assert(offsetof(JSFrameRegisterState,iterator_checkpoint_depth)==164 && sizeof(JSFrameRegisterState)==168,"leaf release checkpoint count");
#endif
extern int JS_FrameIteratorSlowNext(JSContext *ctx,JSValue *sp,int offset);
extern int JS_FrameIteratorSlow(JSFrameRegisterState *state);
extern int JS_FrameIteratorOp_for_of_next(JSFrameRegisterState *state);
extern int JS_FrameIteratorCheckpointSlow(JSFrameRegisterState *state);
extern int JS_FrameIteratorCheckpointOp(JSFrameRegisterState *state);
static FRAME_INLINE JSValue js_frame_iterator_checkpoint_getfield(JSContext *ctx,JSValueConst obj,JSAtom atom)
{
    JSObject *p=JS_VALUE_GET_OBJ(obj);
    JSProperty *property;
    JSShapeProperty *shape_property;
    /* Interp's get-by-id checkpoint: live own data fields are a leaf read.
       Accessors, prototypes, proxies and every exotic object use the exact
       original property operation, after each preceding observable effect. */
    if(p->class_id==JS_CLASS_OBJECT && !p->is_exotic) {
        shape_property=find_own_property(&property,p,atom);
        if(shape_property && !(shape_property->flags&JS_PROP_TMASK))return js_dup(property->u.value);
    }
    return JS_GetProperty(ctx,obj,atom);
}
static FRAME_INLINE bool js_frame_iterator_checkpoint_admit(JSFrame *frame,JSValue *sp,int offset)
{
    JSFunctionBytecode *b=frame->bytecode;
    JSObject *method;
    if (!JS_IsObject(sp[offset]) || !JS_IsObject(sp[offset+1]))return false;
    method=JS_VALUE_GET_OBJ(sp[offset+1]);
    if(method->class_id!=JS_CLASS_BYTECODE_FUNCTION)return false;
    if(!(FRAME_ITERATOR_KIND(b)&64)) {
        FRAME_ITERATOR_KIND(b)|=64;
        if(!getenv("QJS_DISABLE_FRAME_ITERATOR_JS_CALL"))FRAME_ITERATOR_KIND(b)|=32;
    }
    if(!(FRAME_ITERATOR_KIND(b)&32))return false;
    return js_frame_target(sp[offset+1])!=NULL;
}
"""
    helpers += r"""
FRAME_CODE bool JS_FrameIteratorCheckpointAdmit(JSFrame *frame,JSValue *sp,int offset)
{
    return js_frame_iterator_checkpoint_admit(frame,sp,offset);
}
"""
    selectors = r"""
/* Calls to the inherited C slow step can occur after ordinary/native JS
   returns, with no opcode-entry bridge. Detect the typed continuation there
   as well. Never upcast a public outer SF; js_frame_parent stops at the root. */
FRAME_CODE int JS_FrameIteratorCheckpointSelect(JSFrameRegisterState *state)
{
    JSFrame *frame=state->frame;
    if(!state->exception_pending && *state->pc==OP_for_of_next &&
       (FRAME_CHECKPOINT(frame) || js_frame_iterator_checkpoint_admit(frame,state->sp,-3-state->pc[1])))
        return JS_FrameIteratorCheckpointOp(state);
    /* The outer varargs selector retains the complete active protocol. */
    return JS_FrameIteratorSlow(state);
}
FRAME_CODE int JS_FrameIteratorCheckpointOp(JSFrameRegisterState *state)
{
    JSFrame *frame=state->frame;
    if(FRAME_CHECKPOINT(frame)) {
        JSContext *ctx=frame->bytecode->realm;
        JSValue *sp=frame->sf.cur_sp;
        JSValue obj=sp[0],value;
        int done,offset=-3-state->pc[1];
        js_frame_begin_c(state);
        FRAME_CLEAR_CHECKPOINT(frame);
        state->iterator_checkpoint_depth--;
        state->pc+=2;
        frame->sf.cur_pc=state->pc;
        frame->saved_sp=sp;
        state->sp=sp;
        value=JS_FrameIteratorCheckpointValue(ctx,obj,&done);
        if(done || JS_IsException(value)) {
            JS_FreeValue(ctx,sp[offset]);sp[offset]=JS_UNDEFINED;
            if(JS_IsException(value)) {
                state->exception_pending=true;
                js_frame_finish_c(state);
                return JS_FrameIteratorSlow(state);
            }
            JS_FreeValue(ctx,value);value=JS_UNDEFINED;
        }
        sp[0]=value;sp[1]=js_bool(done);state->sp=sp+2;
        frame->saved_sp=sp+2;
        js_frame_finish_c(state);
        return 0;
    }
    if(js_frame_iterator_checkpoint_admit(frame,state->sp,-3-state->pc[1]))
        return JS_FrameIteratorCheckpointPush(state);
    return JS_FrameIteratorOp_for_of_next(state);
}
"""
    counters = module(source, "generate-slow").COUNTERS
    stats = (
        "\n#ifdef QJS_INTERP_FRAME_DIAGNOSTICS\n"
        + "".join(
            "    "
            + (
                "unsigned"
                if n in ("depth", "max_depth")
                else "size_t"
                if n == "peak_bytes"
                else "uint64_t"
            )
            + " "
            + n
            + "=state->"
            + n
            + ";\n"
            for n in counters
        )
        + "#endif\n"
    )
    footer_start = slow.index("slow_step_done:")
    footer = slow[footer_start : slow.index("\n#undef CASE", footer_start)]
    enter = slow[slow.index("enter_frame:\n") : slow.index("dispatch:\n")]
    push = (
        r"""
FRAME_CODE int JS_FrameIteratorCheckpointPush(JSFrameRegisterState *state)
{
    JSFrame *frame=state->frame,*parent;
    JSFrameSegment *segment=state->segment;
    JSRuntime *rt=state->rt;
    JSContext *ctx=frame->bytecode->realm;
    JSStackFrame *sf=&frame->sf;
    JSValue *sp=state->sp,*arg_buf,*var_buf,*stack_buf,*local_buf;
    int offset=-3-state->pc[1],i,owned_args,incoming_argc=0,incoming_copy=0,event=0;
    JSValue func_obj=sp[offset+1],this_obj=sp[offset],ret_val=JS_UNDEFINED;
    JSValueConst *incoming_argv=vc(sp+2);
    JSFunctionBytecode *b=JS_VALUE_GET_OBJ(func_obj)->u.func.function_bytecode;
    uint8_t *pc=state->pc;
    size_t frame_size,used_bytes=state->used_bytes;
STATS
    js_frame_begin_c(state);
    sf->cur_sp=sp;
    FRAME_SET_CHECKPOINT(frame);
    state->iterator_checkpoint_depth++;
    sf->cur_pc=pc;
    /* IteratorRecord's existing strong slots own both borrowed values until
       this child has returned/unwound. No output-slot Dup/Free is needed.
       The ordinary pending-zero return writes its owned result at sp. */
    frame->saved_sp=sp;
    frame->pending=0;
ENTER
    goto slow_step_done;
push_exception:
    state->frame=frame;state->segment=segment;state->used_bytes=used_bytes;
    state->pc=frame->sf.cur_pc;state->sp=frame->saved_sp;
    state->exception_pending=true;
    js_frame_finish_c(state);
    return JS_FrameIteratorSlow(state);
FOOTER
""".replace("STATS", stats)
        .replace("ENTER", enter)
        .replace("FOOTER", footer)
    )
    value = value.replace(
        "JS_GetProperty(ctx, obj,", "js_frame_iterator_checkpoint_getfield(ctx, obj,"
    )
    out.write_text(prefix + helpers + value + push + slow + selectors, encoding="utf-8")
    (
        _frame_generated_file(build, "quickjs-interpreter-iterator-checkpoint-source.json")
    ).write_text(
        json.dumps(
            dict(
                generated_sha256=sha(out),
                parent_generated_sha256=sha(inherited),
                core_sha256=sha(_frame_source_file(source, "quickjs.c")),
                next_value_tail_sha256=hashlib.sha256(tail.encode()).hexdigest(),
                physical_frame_bytes=128,
                release_state_bytes=168,
                continuation="Private SF byte63 tags actual next continuations; cur_sp independently retains the real GC-visible operand top. All constructors initialize the tag; active slow work uses the complete varargs protocol.",
                control="QJS_DISABLE_FRAME_ITERATOR_JS_CALL",
                configuration_bits=dict(enabled=32, initialized=64),
                ownership="IteratorRecord strong slots own borrowed this/next; pending0; original normal return writes at the reserved output top.",
                return_pc="Original for_of_next opcode, no synthetic bytecode, no ordinary return branch.",
                push_policy="Exact inherited enter_frame body in a dedicated helper; full C opcode switch is reserved for exception-sensitive slow steps.",
                property_policy="Live own normal data fields; original get-property for getters, prototypes and exotics.",
            ),
            indent=2,
        )
        + "\n"
    )
    append_leaf(source, build)


def append_leaf(source, build):
    from native_abi import current_or_load as load_layout

    fields = load_layout(source)["offsets"]
    ops = [
        m[1]
        for m in re.finditer(
            r"^DEF\(\s*(\w+)\s*,",
            _frame_source_file(source, "quickjs-opcode.h").read_text(encoding="utf-8"),
            re.M,
        )
    ]
    records = json.loads((_frame_build_file(build, "compile_commands.json")).read_text())
    error = 2296 if any("QJS_INTERP_FRAME_DIAGNOSTICS" in r["command"] for r in records) else 160
    depth = error + 4
    name = "JS_FrameIteratorCheckpointSelectEntry"
    yes = "JS_FrameIteratorCheckpointSelect"
    no = "JS_FrameIteratorSlow"
    code = [
        ".intel_syntax noprefix",
        '.section .qjsitcp,"xr"',
        ".p2align 4",
        ".globl " + name + ", " + name + "_end",
        ".def " + name + "; .scl 2; .type 32; .endef",
        name + ":",
        "cmp DWORD PTR [rcx+" + str(depth) + "], 0",
        "jne " + yes,
        "mov rax, QWORD PTR [rcx]",
        "mov rax, QWORD PTR [rax+80]",
        f"test BYTE PTR [rax+{fields['JSFunctionBytecode.byte_code_buf'] - 2}], 32",
        "je " + no,
        "cmp BYTE PTR [rcx+" + str(error) + "], 0",
        "jne " + no,
        "mov rdx, QWORD PTR [rcx+16]",
        "cmp BYTE PTR [rdx], " + str(ops.index("for_of_next")),
        "jne " + no,
        "movzx edx, BYTE PTR [rdx+1]",
        "add edx, 2",
        "shl rdx, 4",
        "neg rdx",
        "add rdx, QWORD PTR [rcx+24]",
        "cmp DWORD PTR [rdx+8], -1",
        "jne " + no,
        "mov rdx, QWORD PTR [rdx]",
        f"cmp WORD PTR [rdx+{fields['JSObject.class_id']}], 13",
        "jne " + no,
        "jmp " + yes,
        name + "_end:",
        ".p2align 2",
        name + "_unwind:",
        ".byte 1, 0, 0, 0",
        '.section .qjsicfn$1,"dr"',
        ".p2align 2",
        ".rva " + name + ", " + name + "_end, " + name + "_unwind",
    ]
    # Native/generator next never needs the C admission/checkpoint wrapper.
    # Tail-transfer to the original opcode helper after volatile leaf guards.
    # A returned JS result always has the current frame's typed marker.
    name = "JS_FrameIteratorCheckpointOpEntry"
    yes = "JS_FrameIteratorCheckpointOp"
    no = "JS_FrameIteratorOp_for_of_next"
    code += [
        '.section .qjsitcp,"xr"',
        ".p2align 4",
        ".globl " + name + ", " + name + "_end",
        ".def " + name + "; .scl 2; .type 32; .endef",
        name + ":",
        "mov rax, QWORD PTR [rcx]",
        "test BYTE PTR [rax+63], 2",
        "jne " + yes,
        "mov rdx, QWORD PTR [rcx+16]",
        "movzx eax, BYTE PTR [rdx+1]",
        "add eax, 2",
        "shl rax, 4",
        "neg rax",
        "add rax, QWORD PTR [rcx+24]",
        "cmp DWORD PTR [rax+8], -1",
        "jne " + no,
        "mov rax, QWORD PTR [rax]",
        f"cmp WORD PTR [rax+{fields['JSObject.class_id']}], 13",
        "je " + yes,
        "jmp " + no,
        name + "_end:",
        ".p2align 2",
        name + "_unwind:",
        ".byte 1, 0, 0, 0",
        '.section .qjsicfn$1,"dr"',
        ".p2align 2",
        ".rva " + name + ", " + name + "_end, " + name + "_unwind",
    ]
    (_frame_generated_file(build, "quickjs-interpreter-iterator-checkpoint-win64.S")).write_text(
        "\n".join(code) + "\n", encoding="utf-8"
    )


def fixed_rsp_unwind(coff, objdump, path, function_name):
    """Describe this fixed-SP function without GCC's early FP save base.

    GCC establishes RBP before fixed allocation, but emits positive XMM save
    offsets relative to final RSP. Windows applies a nonzero FP base to those
    saves. All new Slow body SP writes are certified epilogues, so a fixed-RSP
    descriptor is exact: retain push/alloc/XMM codes and remove SET_FPREG.
    """
    slow = coff.symbols[function_name]
    found = []
    for rec in coff.section_records:
        rel = {
            struct.unpack_from("<I", coff.data, rec["reloc"] + 10 * i)[0]: coff.all_symbols[
                struct.unpack_from("<I", coff.data, rec["reloc"] + 10 * i + 4)[0]
            ]
            for i in range(rec["count"])
        }
        for off in range(0, rec["size"] - 11, 12):
            if off not in rel or off + 8 not in rel:
                continue
            begin = rel[off]
            lo = begin["value"] + struct.unpack_from("<I", coff.data, rec["raw"] + off)[0]
            if begin["section"] != slow["section"] or lo != slow["value"]:
                continue
            end = rel[off + 4]
            hi = end["value"] + struct.unpack_from("<I", coff.data, rec["raw"] + off + 4)[0]
            u = rel[off + 8]
            ur = coff.section_records[u["section"] - 1]
            at = (
                ur["raw"]
                + u["value"]
                + struct.unpack_from("<I", coff.data, rec["raw"] + off + 8)[0]
            )
            found.append((lo, hi, at))
    assert len(found) == 1, found
    lo, hi, at = found[0]
    header = bytes(coff.data[at : at + 4])
    version, prolog, count, fp = header
    assert version == 1
    if fp == 0:
        return dict(
            function=function_name, needed=False, scope="Compiler fixed-RSP descriptor retained."
        )
    assert fp == 5, ("new fixed-SP descriptor gate", header.hex())
    before = bytes(coff.data[at : at + 4 + 2 * ((count + 1) & ~1)])
    kept = []
    i = 0
    sets = 0
    allocation = 0
    while i < count:
        start = i
        op = coff.data[at + 5 + 2 * i] & 15
        info = coff.data[at + 5 + 2 * i] >> 4
        i += 1
        if op in (1, 8):
            extra = 2 if op == 1 and info == 1 else 1
            if op == 1:
                allocation += struct.unpack_from("<I" if info else "<H", coff.data, at + 4 + 2 * i)[
                    0
                ] * (1 if info else 8)
            i += extra
        elif op == 2:
            allocation += 8 * (info + 1)
        else:
            assert op in (0, 3), op
        if op == 3:
            assert coff.data[at + 4 + 2 * start] == 4 and info == 0
            sets += 1
        else:
            kept.append(bytes(coff.data[at + 4 + 2 * start : at + 4 + 2 * i]))
    assert sets == 1 and allocation > 0
    # Decode only the actual code contribution; renamed .rdata/.xdata use the
    # same island name but are not instructions in the function range.
    section_names = []
    for sec in coff.sections:
        n = sec["name"]
        if n.startswith("/"):
            p = int(n[1:])
            n = coff.strings[p : coff.strings.index(0, p)].decode()
        section_names.append(n)
    listing = subprocess.check_output(
        [str(objdump), "-D", "-w", "-Mintel", "-j", section_names[slow["section"] - 1], str(path)],
        text=True,
    )
    occurrence = 0
    sn = None
    inst = []
    matches = [
        i + 1 for i, n in enumerate(section_names) if n == section_names[slow["section"] - 1]
    ]
    for line in listing.splitlines():
        if line.startswith("Disassembly of section "):
            sn = matches[occurrence]
            occurrence += 1
            continue
        m = re.match(r"^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2}\s+)+)\s*(.*?)\s*$", line)
        if m and sn == slow["section"] and lo <= int(m[1], 16) < hi:
            inst.append((int(m[1], 16), m[3]))
    assert inst and inst[0] == (lo, "push   rbp") and inst[1][1] == "mov    rbp,rsp"
    body = [p for p in inst if p[0] - lo >= prolog]
    moves = [p for p in body if re.match(r"(add|sub|lea|mov|and)\s+rsp,", p[1])]
    assert moves and all(
        re.fullmatch(r"add\s+rsp,0x" + format(allocation, "x"), p[1]) for p in moves
    ), moves
    allowed = set()
    for pc, asm in moves:
        j = inst.index((pc, asm))
        allowed.add(pc)
        j += 1
        while j < len(inst) and re.fullmatch(r"pop\s+(rbx|rbp|rsi|rdi|r1[2-5])", inst[j][1]):
            allowed.add(inst[j][0])
            j += 1
        assert j < len(inst) and (inst[j][1] == "ret" or inst[j][1].startswith("jmp "))
    assert all(pc in allowed for pc, asm in body if asm.startswith(("push ", "pop ")))
    codes = b"".join(kept)
    new_count = len(codes) // 2
    after = bytes((version, prolog, new_count, 0)) + codes
    assert len(after) <= len(before)
    after = after.ljust(len(before), b"\0")
    coff.data[at : at + len(before)] = after
    return dict(
        function=function_name,
        needed=True,
        before=before.hex(),
        after=after.hex(),
        instructions=len(inst),
        body_stack_adjustments=moves,
        scope="New fixed-SP Slow unwind only; no instruction changes, no old metadata changes.",
        specification="https://learn.microsoft.com/en-us/cpp/build/exception-handling-x64",
    )


def compile_extra(source, build, out):
    compiler = module(source, "atod")
    old = compiler.win_argv

    def checkpoint_argv(command):
        args = [x for x in old(command) if not x.startswith("-g")]
        return [args[0], "-I" + str(source), "-I" + str(build), *args[1:], "-g0"]

    compiler.win_argv = checkpoint_argv
    compiler.compile_extra(
        source,
        build,
        out,
        generator=lambda src, target: generate(src, build, target),
        filename="quickjs-interpreter-iterator-checkpoint.c",
        late_name=".qjsitcp",
    )
    adapter = module(source, "object-adapter")
    coff = adapter.Coff(out.read_bytes())
    record = out.with_suffix(".compile.json")
    j = json.loads(record.read_text())
    backup = out.with_name(out.name + ".compiler-unwind")
    assert not backup.exists()
    backup.write_bytes(out.read_bytes())
    repair = [
        fixed_rsp_unwind(coff, Path(j["compiler_command"][0]).parent / "objdump.exe", out, n)
        for n in ("JS_FrameIteratorCheckpointSlow", "JS_FrameIteratorCheckpointPush")
    ]
    for rec in coff.section_records:
        for i in range(rec["count"]):
            off, sym, kind = struct.unpack_from("<IIH", coff.data, rec["reloc"] + 10 * i)
            assert kind != 1, ("No new ADDR64 relocation", off, coff.all_symbols[sym]["name"])
    for sn, (sec, rec) in enumerate(zip(coff.sections, coff.section_records), 1):
        name = sec["name"]
        if name.startswith("/"):
            at = int(name[1:])
            name = coff.strings[at : coff.strings.index(0, at)].decode()
        if not name.startswith(".pdata"):
            continue
        at = len(coff.strings)
        coff.strings += b".qjsicfn$0\0"
        coff.data[rec["pos"] : rec["pos"] + 8] = ("/" + str(at)).encode().ljust(8, b"\0")
        for index, symbol in coff.all_symbols.items():
            if (
                symbol["section"] == sn
                and symbol["name"] == name
                and symbol["storage"] == 3
                and symbol["type"] == 0
            ):
                struct.pack_into("<II", coff.data, coff.table + index * coff.stride, 0, at)
    out.write_bytes(coff.finish())
    j.update(
        object_sha256=sha(out),
        no_absolute64_relocations=True,
        pdata_policy="After retained iteration/fast/slow ranges.",
        fixed_rsp_unwind=repair,
        compiler_object_sha256=sha(backup),
    )
    record.write_text(json.dumps(j, indent=2) + "\n")


def route(source, paths, objdump):
    parent = module(source, "iterator")
    targets = {
        "JS_FrameIteratorSlow": "JS_FrameIteratorCheckpointSelectEntry",
        "JS_FrameIteratorOp_for_of_next": "JS_FrameIteratorCheckpointOpEntry",
    }
    for path in paths:
        parent.route(
            path,
            source,
            objdump,
            targets=targets,
            label="iterator-checkpoint",
            excluded_sections=(".qjsitcp",),
            conditional=True,
        )


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, required=True)
    ap.add_argument("--build", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--compile", action="store_true")
    ap.add_argument("--objdump", type=Path)
    ap.add_argument("--route", nargs="*", type=Path)
    a = ap.parse_args()
    if a.compile:
        compile_extra(a.source, a.build, a.out)
    else:
        assert a.route and a.objdump
        route(a.source, a.route, a.objdump)
