"""Interp-style JS next call and done/value return checkpoints.

The paused caller retains its real operand top in cur_sp and has a separate
byte63 bit1 continuation tag, disjoint from C-window bit0 and initialized at every frame constructor. GC visibility
therefore cannot create a false continuation. The combined varargs slow step
owns active-checkpoint exceptions and the ordinary return kernel remains intact. Existing method-call ownership and frames apply.
"""

