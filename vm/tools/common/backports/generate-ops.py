"""Copy supported legacy opcode bodies without changing their semantics."""

import sys as _frame_sys
from pathlib import Path as _FramePath

_frame_tools_root = str(_FramePath(__file__).resolve().parents[2])
if _frame_tools_root not in _frame_sys.path:
    _frame_sys.path.insert(0, _frame_tools_root)
from common.paths import (
    activate_tools as _frame_activate_tools,
    tool_path as _frame_tool_path,
    source_file as _frame_source_file,
    source_text as _frame_source_text,
    generated_file as _frame_generated_file,
    project_root as _frame_project_root,
    build_file as _frame_build_file,
)

_frame_activate_tools()
import argparse, re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--source", type=Path, required=True)
parser.add_argument("--lazy-var-refs", action="store_true")
parser.add_argument("--local-captures", action="store_true")
args = parser.parse_args()
ROOT = args.source
source = _frame_source_file(ROOT, "quickjs.c").read_text(encoding="utf-8")
start = source.index("        CASE(OP_push_i32)")
end = source.index("        CASE(OP_invalid)", start)
body = source[start:end]
matches = list(re.finditer(r"^        CASE\(OP_(\w+)\)", body, re.M))
selected = set(
    """
push_i32 push_bigint_i32 push_const push_minus1 push_0 push_1 push_2 push_3
push_4 push_5 push_6 push_7 push_i8 push_i16 push_const8 push_empty_string
get_length push_atom_value undefined null push_this push_false push_true object fclosure fclosure8
drop nip nip1 dup dup2 dup3 dup1 insert2 insert3 insert4 perm3 rot3l rot4l
rot5l rot3r perm4 perm5 swap swap2 array_from throw throw_error
call_constructor check_ctor
get_var_undef get_var put_var put_var_init
get_loc put_loc set_loc get_arg put_arg set_arg get_loc8 put_loc8 set_loc8
get_loc0_loc1 get_loc0 get_loc1 get_loc2 get_loc3
put_loc0 put_loc1 put_loc2 put_loc3 set_loc0 set_loc1 set_loc2 set_loc3
get_arg0 get_arg1 get_arg2 get_arg3 put_arg0 put_arg1 put_arg2 put_arg3
set_arg0 set_arg1 set_arg2 set_arg3
get_var_ref0 get_var_ref1 get_var_ref2 get_var_ref3
put_var_ref0 put_var_ref1 put_var_ref2 put_var_ref3
set_var_ref0 set_var_ref1 set_var_ref2 set_var_ref3
get_var_ref put_var_ref set_var_ref get_var_ref_check put_var_ref_check
put_var_ref_check_init set_loc_uninitialized get_loc_check put_loc_check
put_loc_check_init goto goto16 goto8 if_true if_false if_true8 if_false8
lnot get_field get_field2 put_field define_field get_array_el get_array_el2
put_array_el define_array_el add add_loc sub mul div mod pow plus neg inc dec
post_inc post_dec inc_loc dec_loc not shl shr sar and or xor in instanceof typeof
delete delete_var to_object to_propkey to_propkey2
is_undefined_or_null is_undefined is_null typeof_is_undefined typeof_is_function
""".split()
)
if args.local_captures:
    selected.add("close_loc")
blocks = []
found = set()
for i, match in enumerate(matches):
    op = match[1]
    if op in selected:
        found.add(op)
        blocks.append(
            body[match.start() : matches[i + 1].start() if i + 1 < len(matches) else len(body)]
        )
assert found == selected, selected - found
# The comparison macro is part of the preceding xor block in the original.
selected.update("lt lte gt gte eq neq strict_eq strict_neq".split())
custom = "call0 call1 call2 call3 call tail_call call_method tail_call_method return return_undef nop".split()
banner = "/* Generated by tools/common/backports/generate-ops.py.\n * Legacy opcode semantics; check_ctor uses the private construction context. */\n"
opcode_body = "".join(blocks)
start = opcode_body.index("        CASE(OP_check_ctor):")
end = opcode_body.index("\n        CASE(", start + 1)
opcode_body = (
    opcode_body[:start]
    + """        CASE(OP_check_ctor):
            if (FRAME_ROOT(frame)!=3) {
                JS_ThrowTypeError(ctx, "class constructors must be invoked with 'new'");
                goto exception;
            }
            BREAK;
"""
    + opcode_body[end:]
)
from qualified_ops import apply as apply_qualified_ops

opcode_body = apply_qualified_ops(opcode_body)

global_get = "                val = JS_GetGlobalVar(ctx, atom, opcode - OP_get_var_undef);"
assert opcode_body.count(global_get) == 1
opcode_body = opcode_body.replace(
    global_get,
    "#ifdef QJS_PROPERTY_IC\n                val = JS_FrameGlobalBindingCellGet(ctx, b, pc - 5, atom, opcode - OP_get_var_undef);\n#else\n                val = JS_GetGlobalVar(ctx, atom, opcode - OP_get_var_undef);\n#endif",
    1,
)

from property_ic import opcode_with_fallback

for name in ("get_field", "get_field2", "put_field"):
    start = opcode_body.index("        CASE(OP_" + name + "):")
    end = opcode_body.index("        CASE(", start + 1)
    original = opcode_body[start:end]
    opcode_body = opcode_body[:start] + opcode_with_fallback(name, original) + opcode_body[end:]
if args.local_captures:
    assert opcode_body.count("close_lexical_var(ctx, b, sf, idx);") == 1
    opcode_body = opcode_body.replace(
        "close_lexical_var(ctx, b, sf, idx);", "js_frame_close_lexical_var(ctx, b, sf, idx);"
    )
if args.lazy_var_refs:
    opcode_body = re.sub(r"\bvar_refs\b", "FRAME_VAR_REFS()", opcode_body)
    ops_banner = "/* Generated by tools/common/backports/generate-ops.py --lazy-var-refs.\n * Legacy opcode semantics; closure-array access uses FRAME_VAR_REFS(). */\n"
else:
    ops_banner = banner


def _write_lf(path, content):
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)


_write_lf(_frame_source_file(ROOT, "quickjs-interpreter-ops.h"), ops_banner + opcode_body)
_write_lf(
    _frame_source_file(ROOT, "quickjs-interpreter-opcodes.h"),
    banner + "".join(f"FRAME_OP({op})\n" for op in sorted(selected | set(custom))),
)
opcodes = re.findall(
    r"^\s*DEF\(\s*(\w+)",
    _frame_source_file(ROOT, "quickjs-opcode.h").read_text(encoding="utf-8"),
    re.M,
)
_write_lf(
    _frame_source_file(ROOT, "quickjs-interpreter-dispatch.h"),
    banner
    + "".join(
        f"FRAME_TARGET({op}, "
        + ("OP_" + op if op in selected or op in custom else "invalid")
        + ")\n"
        for op in opcodes
    ),
)
print(
    f"{len(selected) + len(custom)} supported opcodes; {sum(len(b) for b in blocks)} source bytes"
)
