"""Regenerate inverse regexp folding from this tree's retained Unicode rules.

Development tool, not a configure/build dependency: no target executable is
run by CMake, including cross builds. The small host oracle enumerates the
existing canonicalizer, so Python/OS Unicode versions cannot change semantics.
"""

import argparse
import collections
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile


def generate(root, compiler):
    inputs = [
        "src/common/regexp/unicode/" + name
        for name in ("libunicode.c", "libunicode.h", "libunicode-table.h")
    ]
    oracle = r"""
#include <stdio.h>
#include "src/common/regexp/unicode/regexp-unicode.h"
int main(void) {
    unsigned c, canonical;
    int mode;
    for (mode = 0; mode < 2; mode++) {
        for (c = 0; c <= 0x10ffff; c++) {
            canonical = lre_canonicalize(c, mode != 0);
            if ((unsigned)lre_canonicalize(canonical, mode != 0) != canonical)
                return 2;
            if (c != canonical) printf("%u %u %u\n", mode, c, canonical);
        }
    }
    return 0;
}
"""
    with tempfile.TemporaryDirectory(prefix="qjs-regexp-fold-") as directory:
        directory = Path(directory)
        source = directory / "oracle.c"
        source.write_text(oracle, encoding="utf-8")
        binary = directory / "oracle.exe"
        command = [
            compiler,
            "-O2",
            "-I" + str(root.parent),
            "-I" + str(root),
            str(source),
            str(root / "src/common/regexp/unicode/regexp-unicode.c"),
            "-o",
            str(binary),
        ]
        env = dict(os.environ)
        env["PATH"] = str(Path(compiler).resolve().parent) + os.pathsep + env.get("PATH", "")
        result = subprocess.run(command, capture_output=True, env=env)
        if result.returncode:
            raise RuntimeError(
                str(result.returncode) + ": " + result.stderr.decode(errors="replace")
            )
        output = subprocess.check_output([str(binary)], text=True, env=env)
    mappings = [[], []]
    for line in output.splitlines():
        mode, source, canonical = map(int, line.split())
        mappings[mode].append((source, canonical))
    unicode_text = (root / inputs[-1]).read_text(encoding="utf-8")
    license_start = unicode_text.index("/*\nUNICODE LICENSE V3")
    license_end = unicode_text.index("*/", license_start) + 2
    lines = [
        unicode_text[license_start:license_end],
        "",
        "/* Generated by tools/common/backports/regexp-casefold.py.",
        " * Full preimages of the retained regexp canonicalizer.",
        " * Do not regenerate with Python or operating-system Unicode data.",
    ]
    for name in inputs:
        lines.append(
            " * "
            + name.split("/")[-1]
            + " SHA256 "
            + hashlib.sha256((root / name).read_bytes()).hexdigest()
        )
    lines += [" */", ""]
    for mode, pairs in enumerate(mappings):
        label = "unicode" if mode else "legacy"
        classes = collections.defaultdict(set)
        for source, canonical in pairs:
            classes[canonical].update((canonical, source))
        members, records = [], []
        for canonical, values in sorted(classes.items()):
            records.append((canonical, len(members), len(values)))
            members.extend(sorted(values))
        assert len(members) < 65536
        lines.append("static const uint32_t regexp_fold_" + label + "_members[] = {")
        for i in range(0, len(members), 10):
            lines.append("    " + ", ".join("0x%x" % c for c in members[i : i + 10]) + ",")
        lines += ["};", "static const RegExpFoldClass regexp_fold_" + label + "_classes[] = {"]
        for i in range(0, len(records), 4):
            lines.append("    " + ", ".join("{0x%x, %d, %d}" % r for r in records[i : i + 4]) + ",")
        lines += ["};", "static const uint32_t regexp_fold_" + label + "_domain[] = {"]
        domain = []
        for source, _ in pairs:
            if domain and source == domain[-1]:
                domain[-1] += 1
            else:
                domain.extend((source, source + 1))
        for i in range(0, len(domain), 10):
            lines.append("    " + ", ".join("0x%x" % c for c in domain[i : i + 10]) + ",")
        lines += ["};", ""]
        print(
            label,
            len(pairs),
            "nonidentity mappings,",
            len(records),
            "classes,",
            len(members),
            "members",
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--compiler", default=shutil.which("gcc"))
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    assert args.compiler, "Pass a host GCC-compatible --compiler"
    root = Path(__file__).resolve().parents[3]
    destination = root / "src/common/regexp/unicode/regexp-casefold-data.h"
    content = generate(root, args.compiler)
    if args.check:
        assert destination.read_text(encoding="utf-8") == content, (
            "Regenerate regexp case-fold data"
        )
    else:
        destination.write_text(content, encoding="utf-8", newline="\n")
