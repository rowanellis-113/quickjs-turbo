def block(text, start):
    opening = text.index("{", start)
    depth = 0
    for i in range(opening, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if not depth:
                return text[opening + 1 : i]
    raise AssertionError("Unclosed original operation block")


def multiplication(text):
    """Keep the original OP_mul case; other operations never reach this entry."""
    start = text.index("switch(op)")
    body = block(text, start)
    case = body.index("case OP_mul:") + len("case OP_mul:")
    end = body.index("break;", case)
    original = text[start : text.index("{", start) + len(body) + 2]
    assert original.count("switch(op)") == 1
    return text.replace(original, body[case:end].strip(), 1)


def generate(source):
    text = _frame_source_file(source, "quickjs.c").read_text(encoding="utf-8")
    pieces = [
        "/* Generated by tools/generate-bigint.py. Original core SHA256: "
        + hashlib.sha256(text.encode("utf-8")).hexdigest()
        + " (UTF-8, LF) */\n"
    ]
    for name, function in (("add", "js_add_slow"), ("mul", "js_binary_arith_slow")):
        start = text.index("static no_inline __exception int " + function + "(")
        end = text.index("\n}\n", start)
        body = text[start:end]
        short = block(
            body, body.index("if (tag1 == JS_TAG_SHORT_BIG_INT && tag2 == JS_TAG_SHORT_BIG_INT)")
        )
        declaration = body.index("        JSBigInt *p1, *p2, *r;")
        big = block(body, body.rfind("{", 0, declaration))
        if name == "mul":
            short = multiplication(short)
            big = multiplication(big).replace("    slow_big_int:\n", "")
        pieces.append(
            """
/* Primitive tags establish that ToPrimitive/ToNumeric are identity operations.
 * All original short arithmetic, allocation, compaction and ownership remain. */
FRAME_PROPERTY_CODE int JS_FrameInterpPrimitive_"""
            + name
            + """(JSFrameRegisterState *state)
{
    JSValue *sp=state->sp;
    JSValue op1=sp[-2], op2=sp[-1];
    uint32_t tag1=JS_VALUE_GET_TAG(op1), tag2=JS_VALUE_GET_TAG(op2);
    JSFrame *frame=state->frame;
    JSStackFrame *sf=&frame->sf;
    JSContext *ctx=frame->bytecode->realm;
    uint8_t *pc=state->pc+1;
"""
        )
        pieces.append(
            """#ifdef QJS_INTERP_FRAME_INTERNAL_ENTRY
    js_frame_begin_c(state);
#endif
    sf->cur_pc=pc;
    if (tag1==JS_TAG_SHORT_BIG_INT && tag2==JS_TAG_SHORT_BIG_INT) {
"""
            + short.replace("return 0;", "goto bigint_done;")
            + "\n    }\n    {\n"
            + big
            + """
    }
bigint_done:
    state->pc=pc;
    state->sp=sp-1;
#ifdef QJS_INTERP_FRAME_INTERNAL_ENTRY
    js_frame_finish_c(state);
#endif
    return 0;
exception:
    /* The copied core operation has consumed both owned inputs on failure. */
    sp[-2]=JS_UNDEFINED;
    sp[-1]=JS_UNDEFINED;
    state->pc=pc;
    state->sp=sp;
    state->exception_pending=true;
#ifdef QJS_INTERP_FRAME_INTERNAL_ENTRY
    js_frame_finish_c(state);
#endif
    return JS_FrameInterpSlow(state);
}

/* No buffers, allocation or context entry before deciding the operand type.
 * Keeping this gate separate lets non-BigInt values tail-enter their original
 * operation without the primitive body's register saves and stack cookie. */
FRAME_PROPERTY_CODE int JS_FrameInterpBig_"""
            + name
            + """(JSFrameRegisterState *state)
{
    JSValue *sp=state->sp;
    if (JS_IsBigInt(sp[-2]) && JS_IsBigInt(sp[-1]))
        return JS_FrameInterpPrimitive_"""
            + name
            + """(state);
    return JS_FrameInterpOp_"""
            + name
            + """(state);
}
"""
        )
    return "".join(pieces)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    value = generate(a.source)
    if a.check:
        assert a.output.read_text(encoding="utf-8") == value, (
            "Generated BigInt boundary does not match original core bodies"
        )
    else:
        a.output.write_text(value, encoding="utf-8", newline="\n")
    print("BIGINT ORIGINAL OPERATION BODIES VERIFIED", flush=True)
