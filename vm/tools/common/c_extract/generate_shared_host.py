def generate(source, *, interpreter_text=None):
    text = (
        _frame_source_text(source, "quickjs-interpreter-loop.h")
        if interpreter_text is None
        else interpreter_text
    )
    host = text[
        text.index("FRAME_CODE int JS_FrameInterpHost(") : text.index(
            "FRAME_HOST_CODE int JS_FrameInterpHostDirect("
        )
    ]
    direct = text[
        text.index("FRAME_HOST_CODE int JS_FrameInterpHostDirect(") : text.index(
            "/* The native return carries an owned value"
        )
    ]
    copied = host + direct
    output = [
        "/* Generated by tools/generate-shared-host.py. MIT.\n * Retained host bodies SHA256: "
        + hashlib.sha256(copied.encode()).hexdigest()
        + "\n * Existing bridges are unchanged. Scope publication surrounds the native call.\n */"
    ]
    for name, body in (("JS_FrameInterpHost", host), ("JS_FrameInterpHostDirect", direct)):
        scoped = name + "Scoped"
        merged = name + "Shared"
        body = body.replace("FRAME_HOST_CODE int " + name, "SHARED_CODE int " + merged).replace(
            "FRAME_CODE int " + name, "SHARED_CODE int " + merged
        )
        at = body.index("\n{") + 2
        prefix = """
    JSRuntime *shared_rt = state->rt;
    JSFrameSharedAnchor **shared_slot, shared_anchor;
    unsigned char shared_active;
    if (!js_frame_shared_enabled(shared_rt))
        return TARGET(state, argv, argc, method);
    if (FRAME_SHARED_BITS(shared_rt) & 8)
        return SCOPED(state, argv, argc, method);
""".replace("TARGET", name).replace("SCOPED", scoped)
        body = body[:at] + prefix + body[at:]
        publish = """shared_slot = js_frame_shared_slot();
        shared_anchor.prev = *shared_slot; shared_anchor.state = state; shared_anchor.kind = 0;
        shared_active = FRAME_SHARED_ACTIVE(shared_rt);
        FRAME_SHARED_BITS(shared_rt) |= 4; *shared_slot = &shared_anchor;"""
        restore = """*shared_slot = shared_anchor.prev;
        FRAME_SHARED_BITS(shared_rt) = (FRAME_SHARED_BITS(shared_rt) & ~4) | shared_active;"""
        if name == "JS_FrameInterpHost":
            marker = "    state->result = js_frame_legacy_call(ctx, argv[-1], this_value, argc, vc(argv));"
            body = replace_one(body, marker, "    " + publish + "\n" + marker + "\n    " + restore)
        else:
            marker = "        ctx = object->u.cfunc.realm;"
            body = replace_one(body, marker, marker + "\n        " + publish)
            marker = "        state->rt->current_stack_frame = host_frame.prev_frame;"
            body = replace_one(body, marker, "        " + restore + "\n" + marker)
        output.append(body)
    return "\n".join(output) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True, type=Path)
    ap.add_argument("--output", required=True, type=Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = generate(a.source)
    if a.check:
        assert a.output.read_text(encoding="utf-8") == data, (
            "Regenerate merged host boundaries from retained source"
        )
    else:
        a.output.write_text(data, encoding="utf-8", newline="\n")
    print(
        "Merged native boundary source verified"
        if a.check
        else "Merged native boundary source generated",
        flush=True,
    )
